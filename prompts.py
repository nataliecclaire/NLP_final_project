"""All prompt templates for the generation stage. Review here; do not inline prompts elsewhere.

Mistral-7B-Instruct-v0.2 is used through its official chat template
(tokenizer.apply_chat_template). We do not use a system message: the
instruction goes in the first user turn.

Rendered factual prompt (Mistral template):
  <s> [INST] {FACTUAL_INSTRUCTION}\n\nQuestion: {fs1_q} [/INST] {fs1_a}</s>
      [INST] Question: {fs2_q} [/INST] {fs2_a}</s>
      [INST] Question: {fs3_q} [/INST] {fs3_a}</s>
      [INST] Question: {question} [/INST]
(line breaks added here for readability only)
"""
from __future__ import annotations

import hashlib
import json

# ---------------------------------------------------------------------------
# Factual QA (TriviaQA, NQ-open, WebQuestions, PopQA) - identical for all.
# ---------------------------------------------------------------------------
FACTUAL_INSTRUCTION = (
    "Answer the question as briefly as possible, using only a few words. "
    "Give just the answer, with no explanation."
)
FACTUAL_QUESTION = "Question: {question}"

# One example per training source, drawn from that source's training side and
# excluded from every split. Generated by scripts/make_splits.py; must match
# data/splits/fewshot.json exactly (enforced at generation time and in tests).
FEWSHOT_EXAMPLES = [
    {"id": "triviaqa-tc_1250",
     "question": "Melanie Molitor is the mom of which tennis world NO 1?",
     "answer": "Martina Hingis"},
    {"id": "nq_open-validation-132",
     "question": "how many gold medals did australia win in the 2000 olympics",
     "answer": "16"},
    {"id": "web_questions-test-593",
     "question": "what kind of disease does montel williams have?",
     "answer": "Multiple sclerosis"},
]

# ---------------------------------------------------------------------------
# GSM8K - zero-shot step-by-step reasoning.
# ---------------------------------------------------------------------------
MATH_TEMPLATE = (
    "Solve the following math problem. Reason step by step, then end your response "
    'with "The answer is <number>." where <number> is the final numeric answer.\n\n'
    "Problem: {question}"
)


def factual_messages(question: str) -> list[dict]:
    msgs = []
    for i, ex in enumerate(FEWSHOT_EXAMPLES):
        q = FACTUAL_QUESTION.format(question=ex["question"])
        if i == 0:
            q = f"{FACTUAL_INSTRUCTION}\n\n{q}"
        msgs.append({"role": "user", "content": q})
        msgs.append({"role": "assistant", "content": ex["answer"]})
    msgs.append({"role": "user", "content": FACTUAL_QUESTION.format(question=question)})
    return msgs


def math_messages(question: str) -> list[dict]:
    return [{"role": "user", "content": MATH_TEMPLATE.format(question=question)}]


def build_messages(task: str, question: str) -> list[dict]:
    if task == "factual":
        return factual_messages(question)
    if task == "math":
        return math_messages(question)
    raise ValueError(task)


def prompt_fingerprint() -> str:
    """Short hash of every template + few-shot example; stored in gen_config."""
    blob = json.dumps([FACTUAL_INSTRUCTION, FACTUAL_QUESTION, FEWSHOT_EXAMPLES, MATH_TEMPLATE],
                      sort_keys=True, ensure_ascii=False)
    return hashlib.sha256(blob.encode()).hexdigest()[:12]
